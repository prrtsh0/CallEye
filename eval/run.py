"""Run the detector over a labeled call split and write eval/report.md.

Usage:
    python -m eval.run --split test
Writes JSON/metrics to stdout and a Markdown report to eval/report.md.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from app.config import DATA_DIR
from app.detector.engine import SessionAnalyzer
from eval.metrics import CallResult, summarize


def load_calls(split: str) -> list[dict]:
    path = DATA_DIR / "calls" / f"{split}.json"
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    # Fall back to fixtures if no explicit split exists.
    docs = []
    for fp in sorted((DATA_DIR / "fixtures").glob("*.json")):
        doc = json.loads(fp.read_text(encoding="utf-8"))
        docs.append(doc)
    return docs


def evaluate(calls: list[dict]) -> list[CallResult]:
    results = []
    for call in calls:
        analyzer = SessionAnalyzer()
        first_alert = None
        for seg in call.get("segments", []):
            res = analyzer.analyze_update(seg["text"], True, float(seg.get("t", 0)))
            if first_alert is None and res.level in ("amber", "red"):
                first_alert = float(seg.get("t", 0))
        results.append(CallResult(
            call_id=call.get("id", "?"),
            label=call.get("label", "genuine"),
            final_level=analyzer.decision.label,
            first_alert_t=first_alert,
            ask_t=call.get("ask_t"),
            reasons=analyzer.decision.screen_text,
        ))
    return results


def render_markdown(metrics: dict, results: list[CallResult]) -> str:
    lines = []
    lines.append("# CallEye evaluation report")
    lines.append("")
    lines.append("Generated by `python -m eval.run --split test`.")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("| --- | --- |")
    labels = [
        ("Calls evaluated", "n_calls"),
        ("Scam calls", "n_scam"),
        ("Genuine calls", "n_genuine"),
        ("Precision", "precision"),
        ("Recall", "recall"),
        ("Accuracy", "accuracy"),
        ("False red", "false_red"),
        ("False amber", "false_amber"),
        ("Avg time-to-alert (s)", "avg_time_to_alert"),
    ]
    for label, key in labels:
        lines.append(f"| {label} | {metrics.get(key)} |")
    lines.append("")
    lines.append("## Misclassifications")
    lines.append("")
    for key, title in (("missed", "Missed scams (green)"),
                        ("false_red_ids", "False red (genuine → red)"),
                        ("false_amber_ids", "False amber (genuine → amber)")):
        ids = metrics.get(key, [])
        lines.append(f"### {title}")
        lines.append("")
        if ids:
            for cid in ids:
                lines.append(f"- {cid}")
        else:
            lines.append("None.")
        lines.append("")
    lines.append("## Per-call detail")
    lines.append("")
    lines.append("| id | label | final | time-to-alert |")
    lines.append("| --- | --- | --- | --- |")
    for r in results:
        lines.append(f"| {r.call_id} | {r.label} | {r.final_level} | {r.time_to_alert} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--split", default="test")
    args = parser.parse_args()

    calls = load_calls(args.split)
    results = evaluate(calls)
    metrics = summarize(results)

    report_dir = Path(__file__).resolve().parent
    (report_dir / "report.md").write_text(
        render_markdown(metrics, results), encoding="utf-8")

    print(json.dumps(metrics, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
